// multipazBundle is testdata/multipaz/reader_auth_all.json: second-edition
// DeviceRequests built and signed by Multipaz's request builder
// (interop/multipaz/driver -fixtures; interop/multipaz/README.md), with
// what each should verify to. It is independent evidence for the
// decoder and verifier: none of its bytes come from this package.
type multipazBundle struct {
	GeneratorVersion       string `json:"generator_version"`
	VerificationTime       string `json:"verification_time"`
	SessionTranscriptBytes []byte `json:"session_transcript_bytes"`
	TrustAnchors           string `json:"trust_anchors"`
	Cases                  []struct {
		Name          string `json:"name"`
		DeviceRequest []byte `json:"device_request"`
		Expected      struct {
			ReaderStatus      string  `json:"reader_status"`
			RequestInfoSigned bool    `json:"request_info_signed"`
			ReaderLeaf        *string `json:"reader_leaf"`
			Documents         []struct {
				DocType  string `json:"doctype"`
				Elements []struct {
					Namespace      string `json:"namespace"`
					Identifier     string `json:"identifier"`
					IntentToRetain bool   `json:"intent_to_retain"`
				} `json:"elements"`
			} `json:"documents"`
			RequestInfo *struct {
				UseCases []struct {
					Mandatory    bool             `json:"mandatory"`
					DocumentSets [][]int          `json:"document_sets"`
					PurposeHints map[string]int32 `json:"purpose_hints"`
				} `json:"use_cases"`
			} `json:"request_info"`
		} `json:"expected"`
	} `json:"cases"`
}

func loadMultipazBundle(tb testing.TB) (multipazBundle, *x509.CertPool, time.Time) {
	tb.Helper()
	raw, err := os.ReadFile("testdata/multipaz/reader_auth_all.json")
	if err != nil {
		tb.Fatal(err)
	}
	var b multipazBundle
	if err := json.Unmarshal(raw, &b); err != nil {
		tb.Fatal(err)
	}
	roots := x509.NewCertPool()
	if !roots.AppendCertsFromPEM([]byte(b.TrustAnchors)) {
		tb.Fatal("no trust anchors in the bundle")
	}
	at, err := time.Parse(time.RFC3339, b.VerificationTime)
	if err != nil {
		tb.Fatal(err)
	}
	if len(b.Cases) == 0 {
		tb.Fatal("no cases in the bundle")
	}
	return b, roots, at
}

// multipazFixtureRequests are the bundle's DeviceRequests, as fuzz seeds.
func multipazFixtureRequests(tb testing.TB) [][]byte {
	tb.Helper()
	b, _, _ := loadMultipazBundle(tb)
	out := make([][]byte, len(b.Cases))
	for i, c := range b.Cases {
		out[i] = c.DeviceRequest
	}
	return out
}

func pemCertificate(tb testing.TB, text string) *x509.Certificate {
	tb.Helper()
	block, _ := pem.Decode([]byte(text))
	if block == nil {
		tb.Fatal("not PEM")
		return nil
	}
	c, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		tb.Fatal(err)
	}
	return c
}

// Each request Multipaz built and signed decodes to the documents and
// information it sent, and verifies, at the bundle's fixed time under
// its test trust anchor, to the reader status and coverage expected.
func TestMultipazFixtures(t *testing.T) {
	b, roots, at := loadMultipazBundle(t)
	t.Logf("generated by %s, verified at %s", b.GeneratorVersion, at)
	trust := ReaderTrust{Roots: roots, LeafPolicy: RequireReaderAuthenticationEKU, Now: at}
	for _, c := range b.Cases {
		t.Run(c.Name, func(t *testing.T) {
			req, err := DecodeDeviceRequest(c.DeviceRequest)
			if err != nil {
				t.Fatalf("DecodeDeviceRequest: %v", err)
			}
			docs := req.DocRequests()
			if len(docs) != len(c.Expected.Documents) {
				t.Fatalf("%d documents, want %d", len(docs), len(c.Expected.Documents))
			}
			for i, want := range c.Expected.Documents {
				got := docs[i]
				if got.DocType != want.DocType || len(got.Elements) != len(want.Elements) {
					t.Fatalf("document %d = %s %v, want %s with %d elements", i, got.DocType, got.Elements, want.DocType, len(want.Elements))
				}
				for j, e := range want.Elements {
					pair := [2]string{e.Namespace, e.Identifier}
					if got.Elements[j] != pair || got.IntentToRetain[pair] != e.IntentToRetain {
						t.Errorf("document %d element %d = %v (retain %v), want %v (retain %v)", i, j, got.Elements[j], got.IntentToRetain[got.Elements[j]], pair, e.IntentToRetain)
					}
				}
			}

			info := req.RequestInfo()
			switch want := c.Expected.RequestInfo; {
			case want == nil && info != nil:
				t.Errorf("RequestInfo = %+v, want nil", info)
			case want != nil && info == nil:
				t.Error("RequestInfo = nil, want present")
			case want != nil:
				if len(info.UseCases) != len(want.UseCases) {
					t.Fatalf("%d use cases, want %d", len(info.UseCases), len(want.UseCases))
				}
				for i, w := range want.UseCases {
					g := info.UseCases[i]
					expected := UseCase{Mandatory: w.Mandatory, DocumentSets: w.DocumentSets, PurposeHints: w.PurposeHints}
					if expected.PurposeHints == nil {
						expected.PurposeHints = map[string]int32{}
					}
					if !equalRequestInfo(&RequestInfo{UseCases: []UseCase{g}}, &RequestInfo{UseCases: []UseCase{expected}}) {
						t.Errorf("use case %d = %+v, want %+v", i, g, expected)
					}
				}
			}

			got := VerifyDeviceRequest(req, b.SessionTranscriptBytes, trust)
			if got.Reader.Status.String() != c.Expected.ReaderStatus || got.RequestInfoSigned != c.Expected.RequestInfoSigned {
				t.Fatalf("VerifyDeviceRequest = %v (%v), signed %v; want %s, signed %v",
					got.Reader.Status, got.Reader.Err, got.RequestInfoSigned, c.Expected.ReaderStatus, c.Expected.RequestInfoSigned)
			}
			if c.Expected.ReaderLeaf != nil && !got.Reader.Chain[0].Equal(pemCertificate(t, *c.Expected.ReaderLeaf)) {
				t.Errorf("the reader is %s, not the expected signer", got.Reader.Chain[0].Subject)
			}
		})
	}
}

// What Multipaz signed stops verifying when anything it covers changes:
// another session, a changed document or information byte, documents
// reordered; and a trusted reader stops being trusted without its
// anchor, or outside its certificate's validity.
func TestMultipazFixtures_Tampered(t *testing.T) {
	b, roots, at := loadMultipazBundle(t)
	trust := ReaderTrust{Roots: roots, LeafPolicy: RequireReaderAuthenticationEKU, Now: at}
	for _, c := range b.Cases {
		if c.Expected.ReaderStatus != "trusted" {
			continue
		}
		t.Run(c.Name, func(t *testing.T) {
			req := mustDecode(t, c.DeviceRequest)
			if got := VerifyDeviceRequest(req, testTranscriptBytes(t, "another session"), trust); got.Reader.Status != ReaderInvalid || got.RequestInfoSigned {
				t.Errorf("another session: %v, signed %v; want invalid", got.Reader.Status, got.RequestInfoSigned)
			}
			if got := VerifyDeviceRequest(req, b.SessionTranscriptBytes, ReaderTrust{Roots: x509.NewCertPool(), Now: at}); got.Reader.Status != ReaderUntrusted || got.RequestInfoSigned != c.Expected.RequestInfoSigned {
				t.Errorf("without its anchor: %v, signed %v; want untrusted, coverage unchanged", got.Reader.Status, got.RequestInfoSigned)
			}
			if got := VerifyDeviceRequest(req, b.SessionTranscriptBytes, ReaderTrust{Roots: roots, Now: at.AddDate(30, 0, 0)}); got.Reader.Status != ReaderUntrusted {
				t.Errorf("after its certificates expire: %v, want untrusted", got.Reader.Status)
			}

			if req.RequestInfo() != nil {
				// A changed hint: the decoded request differs only in what
				// readerAuthAll covers.
				changed := editRequest(t, c.DeviceRequest, func(m map[string]cbor.RawMessage) {
					m["deviceRequestInfo"] = infoOf(t, map[string]any{"useCases": []any{useCase([][]int{{0}}, "purposeHints", map[string]int{"org.example.controller": 4})}})
				})
				if got := VerifyDeviceRequest(mustDecode(t, changed), b.SessionTranscriptBytes, trust); got.Reader.Status != ReaderInvalid || got.RequestInfoSigned {
					t.Errorf("changed information: %v, signed %v; want invalid", got.Reader.Status, got.RequestInfoSigned)
				}
			}
			reordered := editRequest(t, c.DeviceRequest, func(m map[string]cbor.RawMessage) {
				var docs []cbor.RawMessage
				if err := cbor.Unmarshal(m["docRequests"], &docs); err != nil {
					t.Fatal(err)
				}
				docs[0], docs[1] = docs[1], docs[0]
				m["docRequests"] = mustCBOR(t, docs)
			})
			reorderedReq, err := DecodeDeviceRequest(reordered)
			if err != nil {
				// Both documents exist either way: the request still decodes.
				t.Fatalf("reordered: %v", err)
			}
			if got := VerifyDeviceRequest(reorderedReq, b.SessionTranscriptBytes, trust); got.Reader.Status != ReaderInvalid {
				t.Errorf("documents reordered: %v, want invalid", got.Reader.Status)
			}
		})
	}
}

// The motivating gap: the legacy, document-only path sees a request
// Multipaz signed only as a whole as unsigned.
func TestMultipazFixtures_LegacyPathSeesNoSignature(t *testing.T) {
	b, roots, at := loadMultipazBundle(t)
	for _, c := range b.Cases {
		if c.Name != "whole_request_only" {
			continue
		}
		docs, err := ParseDeviceRequest(c.DeviceRequest)
		if err != nil {
			t.Fatal(err)
		}
		if got := VerifyReaderAuth(docs[0], b.SessionTranscriptBytes, ReaderTrust{Roots: roots, Now: at}); got.Status != ReaderUnauthenticated {
			t.Errorf("VerifyReaderAuth = %v, want unauthenticated", got.Status)
		}
		return
	}
	t.Fatal("no whole_request_only case in the bundle")
}
